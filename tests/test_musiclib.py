"""Tests for the parts that do not need Music.app or a real iPod.

The two behaviours worth pinning down are the ones that fail quietly in
production:

  * an import that adds nothing must raise, not report success
  * an unsupported capability must raise before doing work, not no-op
"""

from __future__ import annotations

import os
import struct
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from musiclib import capabilities, convert, itunesdb, scrub  # noqa: E402


class CapabilityTests(unittest.TestCase):
    def test_unsupported_raises_with_reason(self):
        with self.assertRaises(capabilities.Unsupported) as ctx:
            capabilities.require("artist_image")
        self.assertIn("catalog ID", str(ctx.exception))

    def test_supported_does_not_raise(self):
        for cap in capabilities.SUPPORTED:
            capabilities.require(cap)

    def test_matrix_is_machine_readable(self):
        m = capabilities.matrix()
        self.assertEqual(set(m), {"supported", "unsupported"})
        self.assertIn("artist_image", m["unsupported"])
        self.assertIn("lyrics_plain", m["supported"])


class TitleCleaningTests(unittest.TestCase):
    def test_artist_prefix_is_stripped_and_kept(self):
        title, artist, original = convert.clean_title(
            "Artist - Song", "Artist", "Song")
        self.assertEqual(title, "Song")
        self.assertEqual(original, "Artist - Song")

    def test_plain_title_untouched(self):
        self.assertEqual(convert.clean_title("Song", "Artist", "Song - Single"),
                         ("Song", "Artist", None))

    def test_duet_named_after_performers(self):
        title, artist, original = convert.clean_title(
            "Artist - Duet", "Artist", "Duet")
        self.assertEqual(title, "Duet")

    def test_unrelated_prefix_kept(self):
        title, _artist, original = convert.clean_title(
            "Something - Else", "Artist", "Album")
        self.assertEqual(title, "Something - Else")
        self.assertIsNone(original)


class OutnameTests(unittest.TestCase):
    def test_suffix_prevents_collision(self):
        a = convert.outname({"title": "夜曲"}, 1)
        b = convert.outname({"title": "夜曲"}, 2)
        self.assertNotEqual(a, b)
        self.assertTrue(a.endswith("夜曲 [001].m4a"))


class iTunesDBTests(unittest.TestCase):
    def test_rejects_non_database(self):
        with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
            f.write(b"not a database at all")
            path = f.name
        try:
            with self.assertRaises(itunesdb.NotAnITunesDB):
                list(itunesdb.parse(path))
        finally:
            os.unlink(path)

    def test_rejects_length_mismatch(self):
        with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
            f.write(b"mhbd" + struct.pack("<II", 12, 9999))
            path = f.name
        try:
            with self.assertRaises(itunesdb.NotAnITunesDB):
                list(itunesdb.parse(path))
        finally:
            os.unlink(path)

    def test_has_art_on_missing_file(self):
        self.assertFalse(itunesdb.has_art("/nonexistent/file.aiff"))

    def test_normalize_path(self):
        rec = {"path": ":iPod_Control:Music:F04:RWZF.aif", "title": "t"}
        out = itunesdb.normalize(rec)
        self.assertEqual(out["relpath"], "F04/RWZF.aif")
        self.assertEqual(out["source"], "iPod_Control:Music:F04:RWZF.aif")

    def test_missing_art_is_false_not_error(self):
        rec = {"path": ":iPod_Control:Music:none:none.aif"}
        out = itunesdb.normalize(rec, music_root="/tmp/definitely-not-here")
        self.assertFalse(out["art"])


class ScrubTests(unittest.TestCase):
    """Every case is a string taken from a real file."""

    def _clean(self, field, value):
        return scrub.scrub({field: value}).tags[field]

    def test_vendor_signature(self):
        self.assertEqual(
            self._clean("description", "Packed by Bilibili XCoder v2.0.2"), "")

    def test_vendor_site_domain(self):
        self.assertEqual(self._clean("comment", "Generated by SSSTWITTER.COM"), "")

    def test_download_site_brackets(self):
        self.assertEqual(
            self._clean("title", "[SomeSite.Com] [某演讲] [1745978100] "),
            "[某演讲]")

    def test_share_solicit_parenthetical(self):
        self.assertEqual(
            self._clean("album", "某歌手（资源分享） - 某会议实录"),
            "某歌手 - 某会议实录")

    def test_bilibili_id(self):
        self.assertEqual(self._clean("title", "歌名_BV1e54y1i7He"), "歌名")

    def test_bare_domain(self):
        self.assertEqual(self._clean("artist", "SoundJay.com Sound Effects"),
                         "Sound Effects")

    def test_two_urls_in_one_field(self):
        text = ("Licensed to the public under http://a.example/lic "
                "verify at http://b.example/x.php?c=1")
        out = self._clean("copyright", text)
        self.assertNotIn("http", out)
        self.assertIn("Licensed to the public under", out)

    def test_xml_metadata_block_removed(self):
        self.assertEqual(
            self._clean("id3v2_priv.XMP", '<?xpacket begin="" id="W5M0Mp" ?>'), "")

    def test_whole_field_ad_removed(self):
        ad = ("moomoo新年大礼包倒计时：30股免费股票\n【美国居民】开户链接：x\n"
              "入金$2000可获得30股免费股票，限时大放送，注册即送现金券")
        self.assertEqual(self._clean("synopsis", ad), "")

    def test_ordinary_title_untouched(self):
        self.assertEqual(self._clean("title", "Song"), "Song")
        self.assertEqual(self._clean("artist", "Artist"), "Artist")

    def test_album_with_dot_io_not_destroyed(self):
        # .io 结尾的专辑名不该被裸域名规则误伤
        self.assertEqual(self._clean("album", "OK Computer"), "OK Computer")

    def test_identity_field_scrubbed_with_fallback(self):
        # 洗得掉就洗，洗空就用占位名——曲目不能没名字，但广告也不能留
        self.assertEqual(self._clean("title", "https://example.com/x"), "Untitled")
        self.assertEqual(self._clean("artist", "@some_handle"), "Unknown Artist")
        self.assertEqual(self._clean("album", "某站.com"), "Unknown Album")

    def test_identity_field_partial_ad_kept_and_cleaned(self):
        self.assertEqual(self._clean("artist", "SoundJay.com Sound Effects"),
                         "Sound Effects")
        self.assertEqual(self._clean("album", "某歌手（资源分享）"), "某歌手")

    def test_input_dict_not_mutated(self):
        tags = {"comment": "Packed by Bilibili XCoder v2.0.2"}
        scrub.scrub(tags)
        self.assertEqual(tags["comment"], "Packed by Bilibili XCoder v2.0.2")


class CleanMetadataTests(unittest.TestCase):
    def test_original_title_preserved(self):
        track, findings = convert.clean_metadata(
            {"title": "[Site.Com] 真歌名", "artist": "某人"})
        self.assertEqual(track["title"], "真歌名")
        self.assertEqual(track["original_title"], "[Site.Com] 真歌名")
        self.assertTrue(findings)

    def test_clean_track_reports_nothing(self):
        track, findings = convert.clean_metadata({"title": "Song", "artist": "Artist"})
        self.assertEqual(findings, [])
        self.assertNotIn("original_title", track)


class CoverFetcherTests(unittest.TestCase):
    def test_unavailable_when_binary_missing(self):
        f = convert.CoverFetcher(binary="")
        self.assertFalse(f.available)
        self.assertIsNone(f.fetch("Artist", "Album", "/tmp"))

    def test_missing_arguments_fetch_nothing(self):
        f = convert.CoverFetcher()
        self.assertIsNone(f.fetch("", "21", "/tmp"))
        self.assertIsNone(f.fetch("Artist", "", "/tmp"))


if __name__ == "__main__":
    unittest.main()
