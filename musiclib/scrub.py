"""Strip advertising and watermark text out of embedded metadata.

Download sites, video rippers and re-uploaders leave fingerprints in the tags,
and the tags travel with the file into every library that imports it:

    description  "Packed by Bilibili XCoder v2.0.2"
    comment      "Generated by SSSTWITTER.COM"
    comment      "converted by convert2mp3.net"
    album        "某歌手（资源分享） - 某会议实录"
    title        "[SomeSite.Com] [某演讲] [1745978100] "

Everything matching a watermark pattern is removed. The only thing kept is a
title / artist / album that would otherwise be left empty, because a track with
no name breaks the library and is harder to fix than an ad in the name.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

#: 只读字段，改了没意义。其余字符串字段一律检查——漏网的广告大多藏在
#: synopsis / description / copyright / id3v2_priv.* 这类冷门字段里。
SKIP_FIELDS = ("major_brand", "minor_version", "compatible_brands", "duration",
               "bit_rate", "size", "nb_streams", "format_name",
               "format_long_name", "start_time", "probe_score")

#: Fields the library identifies a track by. Scrubbing these is wanted — the
#: ad is in the name, so it has to come out of the name — but a name that ends
#: up empty is a different problem: the track can no longer be found to fix.
#: So these keep a floor rather than being exempt.
IDENTITY = ("title", "artist", "album")

#: When scrubbing would empty an identity field, fall back to whatever text
#: survives inside it, else to this.
FALLBACK = {
    "title": "Untitled",
    "artist": "Unknown Artist",
    "album": "Unknown Album",
}

PATTERNS = [
    # [BraveDown.Com] / 【某站.com】
    (re.compile(r"\s*[\[【][^\]】]*\.(?:com|net|io|cn|org|tv|me)\b[^\]】]*[\]】]", re.I),
     "站点名在方括号里"),
    # http://… / www.…  （不吞掉其后的标点，否则相邻两段会粘在一起）
    (re.compile(r"\s*(?:https?://|www\.)[^\s,，。;；、)）\]】]+", re.I), "网址"),
    # Packed by / Generated by / converted by …（含其后的站点名）
    (re.compile(r"\b(?:Packed|Generated|Converted|Ripped|Encoded|Uploaded)"
                r"\s+by\s+[\w.\-]+(?:\s+[\w.\-]+)*", re.I), "工具/站点签名"),
    # SoundJay.com / 某站.cn 这类裸域名。标签部分允许非 ASCII，中文站名也要能认；
    # 后面紧跟 / : 的交给上面的 URL 规则，避免把路径切碎。
    (re.compile(r"\s*[\w\u4e00-\u9fff][\w\u4e00-\u9fff.-]*"
                r"\.(?:com|net|cn|org|tv|io|me)(?:\.[a-z]{2})?(?![./:\w])", re.I),
     "裸域名"),
    # 下载站话术，带括号的整体删
    (re.compile(r"\s*[（(\[【][^）)\]】]*(?:资源分享|免费下载|更多资源|关注公众号|"
                r"微信公众号|加微信|扫码关注|QQ群)[^）)\]】]*[）)\]】]"), "下载站话术"),
    (re.compile(r"(?:资源分享|免费下载|更多资源|关注公众号|微信公众号|加微信|扫码关注)"),
     "下载站话术"),
    (re.compile(r"QQ群[:：]?\s*\d+"), "QQ 群号"),
    # 引流话术：开户链接 / 邀请码 / 加小助手 / join this channel
    (re.compile(r"[^\n。；;]{0,40}?(?:开户链接|邀请链接|注册链接|专属链接|加入.{0,8}频道|"
                r"Join this channel)[^\n。；;]{0,80}", re.I), "引流话术"),
    # _BV1e54y1i7He
    (re.compile(r"\s*_?BV[0-9A-Za-z]{10}\b"), "B 站视频号"),
    # [1745978100]
    (re.compile(r"\s*\[\d{10,13}\]"), "时间戳后缀"),
    # 歌名 - example.com
    (re.compile(r"\s*[-–—_|]\s*[a-z0-9-]+\.(?:com|net|cn|io|tv|me)\s*$", re.I),
     "结尾站点名"),
    # 整段只是一个 @handle
    (re.compile(r"^\s*@[A-Za-z0-9_.-]{2,30}\s*$"), "社交账号"),
]

#: 形如 <meta>/<?xpacket> 的 XML 元数据块，不是给人看的字段，整段删。
JUNK_BLOCK = re.compile(r"<\?xpacket|<x:xmpmeta|<rdf:RDF", re.I)

#: 整个字段里广告占比超过这个比例，就整段清空而不是逐句抠。
#: 一个描述里塞了开户入金送股票，抠掉广告剩下的也不是描述。
AD_RATIO = 0.4
AD_WORDS = re.compile(r"开户|入金|股票|现金券|送|福利|优惠|注册|邀请码?|佣金|免佣|"
                      r"年化|APY|bonus|sign\s*up|referral", re.I)


@dataclass
class Finding:
    field: str
    matched: str
    why: str
    before: str
    after: str

    def as_dict(self) -> dict:
        return {"field": self.field, "matched": self.matched, "why": self.why,
                "before": self.before, "after": self.after}


@dataclass
class ScrubResult:
    tags: dict = field(default_factory=dict)
    findings: list = field(default_factory=list)

    @property
    def changed(self) -> bool:
        return bool(self.findings)

    def as_dict(self) -> dict:
        return {"changed": self.changed,
                "findings": [f.as_dict() for f in self.findings]}


def _tidy(text: str) -> str:
    """Collapse what removing a match leaves behind."""
    text = re.sub(r"[（(\[【]\s*[）)\]】]", "", text)      # 空括号
    text = re.sub(r"\s{2,}", " ", text)
    text = re.sub(r"[\s\-–—_|,，、:：]+$", "", text)      # 结尾的连接符
    text = re.sub(r"\s+(?:under|at|from|by|via|see)$", "", text, flags=re.I)
    text = re.sub(r"(?:详见|来源|出处|见|点击)$", "", text)
    return text.strip(" -–—_|,，、:：")


def _ad_heavy(text: str) -> bool:
    """Whether a field is mostly advertising rather than information.

    A description that is 80% "开户送股票、入金返现" is not a description with
    an ad attached; it is an ad, and combing it out leaves debris. Counting the
    ad vocabulary against the whole field is cruder than parsing it and, on a
    real corpus, removes the right ones.
    """
    if len(text) < 40:
        return False
    hits = len(AD_WORDS.findall(text))
    return hits / max(1, len(text) / 12) > AD_RATIO


def _clean_field(name: str, value: str, findings: list) -> str:
    original = value

    def _blank(why: str) -> str:
        """Clear the field, keeping a name if the library needs one."""
        replacement = FALLBACK[name] if name in IDENTITY else ""
        findings.append(Finding(name, value[:40] + "…", why, original, replacement))
        return replacement

    if JUNK_BLOCK.search(value):
        return _blank("XML 元数据块")

    if _ad_heavy(value):
        return _blank("整段是广告")

    for pattern, why in PATTERNS:
        # 同一条规则在同一字段里可能命中多次（一段里有两个网址），循环到干净为止。
        while True:
            m = pattern.search(value)
            if not m:
                break
            candidate = _tidy(value[:m.start()] + value[m.end():])
            if name in IDENTITY and not candidate:
                candidate = FALLBACK[name]  # 洗，但不能洗完没名字
            if candidate == value:
                break
            findings.append(Finding(name, m.group(0).strip(), why, original,
                                    candidate))
            value = candidate
    return value


def scrub(tags: dict) -> ScrubResult:
    """Return cleaned tags plus a record of every change. Input is not modified."""
    out = dict(tags)
    result = ScrubResult(tags=out)
    for name in list(out):
        if name.lower() in SKIP_FIELDS:
            continue
        value = out.get(name)
        if not isinstance(value, str) or not value.strip():
            continue
        cleaned = _clean_field(name.lower(), value, result.findings)
        if cleaned != value:
            out[name] = cleaned
    return result


def scan(tags: dict) -> list:
    return scrub(tags).findings


def is_clean(tags: dict) -> bool:
    return not scan(tags)
